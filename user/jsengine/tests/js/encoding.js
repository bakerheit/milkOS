test('TextEncoder', function () {
  var e = new TextEncoder();
  assertEq(e.encoding, 'utf-8');
  assertEq(Array.from(e.encode('hé€😀')), [104, 195, 169, 226, 130, 172, 240, 159, 152, 128]);
  assertEq(e.encode('') instanceof Uint8Array, true);
  assertEq(e.encode().length, 0);
  assertEq(e.encode(undefined).length, 0);
  assertEq(Array.from(e.encode('a\ud800b')), [97, 239, 191, 189, 98], 'lone surrogate');
  assertEq(Array.from(e.encode('\udc00')), [239, 191, 189]);
  assertEq(Array.from(e.encode(12)), [49, 50]);
  var dest = new Uint8Array(5);
  var r = e.encodeInto('a€😀', dest);
  assertEq(r.read, 2); assertEq(r.written, 4);
  assertEq(Array.from(dest), [97, 226, 130, 172, 0]);
  r = e.encodeInto('😀😀', new Uint8Array(6));
  assertEq(r.read, 2); assertEq(r.written, 4);
  r = e.encodeInto('abc', new Uint8Array(0));
  assertEq(r.read, 0); assertEq(r.written, 0);
  assertThrows(TypeError, function () { e.encodeInto('a', new Uint16Array(2)); });
  assertThrows(TypeError, function () { TextEncoder(); });
  assertEq(Object.prototype.toString.call(e), '[object TextEncoder]');
  // a view on a bigger buffer writes only into its own range
  var big = new Uint8Array(8);
  e.encodeInto('xy', big.subarray(3, 6));
  assertEq(Array.from(big), [0, 0, 0, 120, 121, 0, 0, 0]);
});
test('TextDecoder utf-8', function () {
  var d = new TextDecoder();
  assertEq(d.encoding, 'utf-8'); assertEq(d.fatal, false); assertEq(d.ignoreBOM, false);
  assertEq(d.decode(new Uint8Array([104, 195, 169, 226, 130, 172, 240, 159, 152, 128])), 'hé€😀');
  assertEq(d.decode(), '');
  assertEq(d.decode(new Uint8Array([0xef, 0xbb, 0xbf, 97])), 'a', 'BOM dropped');
  assertEq(new TextDecoder('utf-8', { ignoreBOM: true }).decode(new Uint8Array([0xef, 0xbb, 0xbf, 97])), '﻿a');
  assertEq(d.decode(new Uint8Array([97, 0xff, 98])), 'a�b');
  assertEq(d.decode(new Uint8Array([0xe2, 0x82])), '�', 'truncated 3-byte sequence is one replacement');
  assertEq(d.decode(new Uint8Array([0xf0, 0x9f, 0x98, 97])), '�a');
  assertEq(d.decode(new Uint8Array([0xc0, 0x80])), '��', 'overlong');
  assertEq(d.decode(new Uint8Array([0xed, 0xa0, 0x80])), '���', 'encoded surrogate');
  assertEq(d.decode(new Uint8Array([0xf4, 0x90, 0x80, 0x80])), '����', 'above U+10FFFF');
  assertEq(d.decode(new Uint8Array([104, 105]).buffer), 'hi');
  assertEq(d.decode(new DataView(new Uint8Array([1, 104, 105, 2]).buffer, 1, 2)), 'hi');
  assertEq(d.decode(new Uint8Array([0, 104, 105, 0]).subarray(1, 3)), 'hi');
  assertThrows(TypeError, function () { d.decode('abc'); });
  assertThrows(TypeError, function () { d.decode([1, 2]); });
  var f = new TextDecoder('utf-8', { fatal: true });
  assertEq(f.fatal, true);
  assertThrows(TypeError, function () { f.decode(new Uint8Array([0xff])); });
  assertThrows(TypeError, function () { f.decode(new Uint8Array([0xe2, 0x82])); });
  assertEq(f.decode(new Uint8Array([0xe2, 0x82, 0xac])), '€');
  assertThrows(RangeError, function () { new TextDecoder('nope'); });
  assertEq(new TextDecoder(' UTF8 ').encoding, 'utf-8');
});
test('TextDecoder streaming', function () {
  var d = new TextDecoder();
  var bytes = new TextEncoder().encode('a€😀b');
  var out = '';
  for (var i = 0; i < bytes.length; i++) out += d.decode(bytes.subarray(i, i + 1), { stream: true });
  out += d.decode();
  assertEq(out, 'a€😀b');
  // BOM only at the very start
  var d2 = new TextDecoder();
  assertEq(d2.decode(new Uint8Array([0xef, 0xbb]), { stream: true }), '');
  assertEq(d2.decode(new Uint8Array([0xbf, 65]), { stream: true }), 'A');
  assertEq(d2.decode(new Uint8Array([0xef, 0xbb, 0xbf]), { stream: true }), '﻿');
  d2.decode();
  assertEq(d2.decode(new Uint8Array([0xef, 0xbb, 0xbf, 66])), 'B', 'state reset after a final decode');
  // a stream cut mid-character flushes a replacement
  var d3 = new TextDecoder();
  assertEq(d3.decode(new Uint8Array([0xe2, 0x82]), { stream: true }), '');
  assertEq(d3.decode(), '�');
});
test('TextDecoder utf-16le and latin1', function () {
  var d = new TextDecoder('utf-16le');
  assertEq(d.encoding, 'utf-16le');
  assertEq(d.decode(new Uint8Array([104, 0, 105, 0])), 'hi');
  assertEq(d.decode(new Uint8Array([0x3d, 0xd8, 0x00, 0xde])), '😀');
  assertEq(d.decode(new Uint8Array([0x3d, 0xd8])), '�', 'lone high surrogate');
  assertEq(d.decode(new Uint8Array([104, 0, 105])), 'h�', 'odd byte');
  assertEq(d.decode(new Uint8Array([0x3d, 0xd8, 0x3d])), '\ufffd', 'a lone high surrogate and an odd byte are one error');
  assertEq(d.decode(new Uint8Array([0x3d, 0xd8, 97, 0])), '\ufffda');
  assertEq(d.decode(new Uint8Array([0xff, 0xfe, 97, 0])), 'a', 'BOM dropped');
  var s = new TextDecoder('utf-16le');
  assertEq(s.decode(new Uint8Array([0x3d]), { stream: true }), '');
  assertEq(s.decode(new Uint8Array([0xd8, 0x00]), { stream: true }), '');
  assertEq(s.decode(new Uint8Array([0xde]), { stream: true }), '😀');
  assertThrows(TypeError, function () { new TextDecoder('utf-16le', { fatal: true }).decode(new Uint8Array([0x3d, 0xd8])); });
  var l = new TextDecoder('latin1');
  assertEq(l.encoding, 'windows-1252');
  assertEq(l.decode(new Uint8Array([0x68, 0xe9, 0x80, 0x9f, 0xff])), 'hé€Ÿÿ');
  assertEq(new TextDecoder('ascii').encoding, 'windows-1252');
  assertEq(new TextDecoder('iso-8859-1').decode(new Uint8Array([0xa0])), ' ');
});
test('btoa and atob', function () {
  assertEq(btoa(''), '');
  assertEq(btoa('f'), 'Zg==');
  assertEq(btoa('fo'), 'Zm8=');
  assertEq(btoa('foo'), 'Zm9v');
  assertEq(btoa('foob'), 'Zm9vYg==');
  assertEq(btoa('\xff\xfe\x00'), '//4A');
  assertEq(btoa(123), 'MTIz');
  assertEq(atob('Zm9vYg=='), 'foob');
  assertEq(atob('Zm9vYg'), 'foob', 'padding is optional');
  assertEq(atob(' Zm9v\nYg == '), 'foob', 'whitespace is dropped');
  assertEq(atob('//4A'), '\xff\xfe\x00');
  assertEq(atob(''), '');
  var e = assertThrows(Error, function () { btoa('Ā'); });
  assertEq(e.name, 'InvalidCharacterError');
  assertEq(assertThrows(Error, function () { atob('Zm9vY'); }).name, 'InvalidCharacterError');
  assertThrows(Error, function () { atob('Zm9v!'); });
  assertThrows(Error, function () { atob('Zm=9'); });
  assertThrows(Error, function () { atob('Zg==='); });
  assertThrows(TypeError, function () { btoa(); });
  var all = '';
  for (var i = 0; i < 256; i++) all += String.fromCharCode(i);
  assertEq(atob(btoa(all)), all);
  assertEq(atob(btoa(all.repeat(40))).length, 256 * 40);
});
test('utf-8 round trip', function () {
  var e = new TextEncoder(), d = new TextDecoder();
  var s = '';
  for (var cp = 1; cp < 0x3000; cp += 7) if (cp < 0xd800 || cp > 0xdfff) s += String.fromCodePoint(cp);
  s += '😀𝄞\u{10ffff}';
  assertEq(d.decode(e.encode(s)), s);
  assertEq(d.decode(e.encode(s.repeat(50))).length, s.length * 50);
});
