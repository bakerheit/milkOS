//! Audio: a small mixer over the virtio-sound driver, `/dev/audio`, `/proc/audio`, and
//! system sounds for the desktop ([`play_system`]). See `docs/audio.md`.
//!
//! Format everywhere: signed 16-bit little endian, 48 kHz, stereo, interleaved (4 bytes per
//! frame). No format negotiation: writers convert (the `play` program does).
//!
//! Every process writing to /dev/audio gets its own **client** (keyed by pid), a 250 ms
//! ring of samples; kernel system sounds get one client each. The "audio" kernel thread
//! mixes all clients (saturating add) into 10 ms periods and hands them to the device; the
//! device returns each period once played, which wakes the thread again, so the pace is
//! the device's. Writers block (sleep) while their ring is full. When everything has
//! drained the stream is stopped; it restarts with the next write.

pub mod wav;

use alloc::collections::VecDeque;
use alloc::string::String;
use alloc::sync::Arc;
use alloc::vec::Vec;
use core::fmt::Write;
use core::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use crate::fs::errno::{Errno, Result};
use crate::fs::node::{Inode, InodeType, Stat, makedev};
use crate::sched::{self, WaitQueue};
use crate::sync::SpinLock;
use crate::virtio::sound::{self, FRAME_BYTES, PERIOD_FRAMES, PERIODS, RATE};
use crate::{kprintln, timer};

/// Per-client buffer: 250 ms.
const RING_SAMPLES: usize = (RATE as usize / 4) * 2;
/// Stop the stream after this long with nothing to play.
const IDLE_STOP_NS: u64 = 200_000_000;
/// Forget a writer's (empty) client after this long without writes.
const CLIENT_GC_NS: u64 = 2_000_000_000;

/// Where the desktop's system sounds live (generated by scripts/gen_sounds.py).
pub const SOUND_DIR: &str = "/System/Library/Sounds";

/// Sounds the desktop can ask for.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Sound {
    Notify,
    Error,
    Chime,
    /// The desktop's screenshot shutter.
    Shutter,
}

impl Sound {
    pub const ALL: [Sound; 4] = [Sound::Notify, Sound::Error, Sound::Chime, Sound::Shutter];
    pub fn file(self) -> &'static str {
        match self {
            Sound::Notify => "notify.wav",
            Sound::Error => "error.wav",
            Sound::Chime => "chime.wav",
            Sound::Shutter => "shutter.wav",
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Key {
    Pid(u32),
    System(u64),
}

struct Client {
    key: Key,
    ring: VecDeque<i16>,
    /// Bytes of a partial frame from the last write.
    carry: [u8; 4],
    ncarry: usize,
    last_write: u64,
    /// System sounds: the whole sound, fed into `ring` as it drains.
    pending: Option<(Arc<Vec<i16>>, usize)>,
    /// Serial number of the last period this client's samples went into.
    last_period: u64,
}

impl Client {
    fn new(key: Key, now: u64) -> Client {
        Client {
            key,
            ring: VecDeque::with_capacity(RING_SAMPLES),
            carry: [0; 4],
            ncarry: 0,
            last_write: now,
            pending: None,
            last_period: 0,
        }
    }
    fn space(&self) -> usize {
        RING_SAMPLES - self.ring.len()
    }
    fn refill(&mut self) {
        let space = self.space();
        if let Some((pcm, pos)) = self.pending.as_mut() {
            let n = space.min(pcm.len() - *pos);
            self.ring.extend(pcm[*pos..*pos + n].iter().copied());
            *pos += n;
            if *pos >= pcm.len() {
                self.pending = None;
            }
        }
    }
    fn idle(&self) -> bool {
        self.ring.is_empty() && self.pending.is_none()
    }
}

struct Mixer {
    clients: Vec<Client>,
    /// Periods handed to the device so far (the next one gets serial `submitted + 1`).
    submitted: u64,
    next_sys: u64,
    last_data: u64,
    frames_mixed: u64,
    starts: u64,
    clipped: u64,
}

static MIXER: SpinLock<Mixer> = SpinLock::new(Mixer {
    clients: Vec::new(),
    submitted: 0,
    next_sys: 0,
    last_data: 0,
    frames_mixed: 0,
    starts: 0,
    clipped: 0,
});
/// The mixer thread sleeps here (device IRQ, new data, system sound requests).
static MIX_WQ: WaitQueue = WaitQueue::new();
/// Writers waiting for ring space, and SNDCTL_DSP_SYNC waiters.
static SPACE_WQ: WaitQueue = WaitQueue::new();
static KICK: AtomicBool = AtomicBool::new(false);
static UP: AtomicBool = AtomicBool::new(false);
static REQUESTS: SpinLock<VecDeque<Sound>> = SpinLock::new(VecDeque::new());
static CACHE: SpinLock<[Option<Arc<Vec<i16>>>; 4]> = SpinLock::new([None, None, None, None]);
static SYS_PLAYED: AtomicU64 = AtomicU64::new(0);

fn kick() {
    KICK.store(true, Ordering::Release);
    MIX_WQ.wake_all();
}

/// virtio-sound interrupt (acked by the driver): a period was played.
pub fn on_device_irq() {
    kick();
}

/// Is there a sound device (and is /dev/audio up)?
pub fn available() -> bool {
    UP.load(Ordering::Acquire)
}

/// Play one of the system sounds (non-blocking; mixed with whatever else plays). For the
/// desktop. Does nothing without a sound device.
pub fn play_system(s: Sound) {
    if !available() {
        return;
    }
    {
        let mut q = REQUESTS.lock();
        if q.len() < 8 {
            q.push_back(s);
        }
    }
    kick();
}

fn load(s: Sound) -> Option<Arc<Vec<i16>>> {
    let k = Sound::ALL.iter().position(|&x| x == s)?;
    if let Some(p) = CACHE.lock()[k].clone() {
        return Some(p);
    }
    let path = alloc::format!("{SOUND_DIR}/{}", s.file());
    let bytes = crate::fs::read_file(&path).ok()?;
    let pcm = Arc::new(wav::decode(&bytes)?);
    CACHE.lock()[k] = Some(pcm.clone());
    Some(pcm)
}

/// Queue PCM bytes for client `key`; returns bytes taken (all, or up to the ring's room).
fn push(m: &mut Mixer, pid: u32, data: &[u8], now: u64) -> usize {
    let key = Key::Pid(pid);
    let c = match m.clients.iter().position(|c| c.key == key) {
        Some(i) => &mut m.clients[i],
        None => {
            m.clients.push(Client::new(key, now));
            m.clients.last_mut().unwrap()
        }
    };
    c.last_write = now;
    let mut used = 0;
    // Finish a partial frame from the previous write first.
    if c.ncarry > 0 {
        if c.space() < 2 {
            return 0;
        }
        let take = (FRAME_BYTES - c.ncarry).min(data.len());
        c.carry[c.ncarry..c.ncarry + take].copy_from_slice(&data[..take]);
        c.ncarry += take;
        used = take;
        if c.ncarry < FRAME_BYTES {
            return used;
        }
        let f = c.carry;
        c.ring.push_back(i16::from_le_bytes([f[0], f[1]]));
        c.ring.push_back(i16::from_le_bytes([f[2], f[3]]));
        c.ncarry = 0;
    }
    let frames = ((data.len() - used) / FRAME_BYTES).min(c.space() / 2);
    let (samples, _) = data[used..used + frames * FRAME_BYTES].as_chunks::<2>();
    for f in samples {
        c.ring.push_back(i16::from_le_bytes(*f));
    }
    used += frames * FRAME_BYTES;
    // A trailing partial frame (only when everything else fit).
    let rest = data.len() - used;
    if rest > 0 && rest < FRAME_BYTES && c.ncarry == 0 {
        c.carry[..rest].copy_from_slice(&data[used..]);
        c.ncarry = rest;
        used += rest;
    }
    used
}

/// write(2) on /dev/audio from process `pid`: blocks until everything is queued.
fn write(pid: u32, data: &[u8]) -> Result<usize> {
    let mut off = 0;
    while off < data.len() {
        let now = timer::now_ns();
        let (n, new_client) = {
            let mut m = MIXER.lock();
            let had = m.clients.iter().any(|c| c.key == Key::Pid(pid));
            (push(&mut m, pid, &data[off..], now), !had)
        };
        if new_client {
            // The first write of a stream (there is no open hook; idle writers are
            // forgotten after 2 s, so this is "started playing").
            crate::audit::record("audio.open", "dev=/dev/audio");
        }
        off += n;
        kick();
        if off < data.len() {
            let key = Key::Pid(pid);
            SPACE_WQ.wait_until_timeout(
                || {
                    MIXER
                        .lock()
                        .clients
                        .iter()
                        .find(|c| c.key == key)
                        .is_none_or(|c| c.space() >= 2 * PERIOD_FRAMES)
                },
                1_000_000_000,
            );
        }
    }
    Ok(data.len())
}

/// SNDCTL_DSP_SYNC: wait until everything `pid` wrote has been played (its last period has
/// come back from the device; periods complete in order). Others may still be playing.
fn drain(pid: u32) {
    let key = Key::Pid(pid);
    let end = timer::now_ns() + 30_000_000_000;
    loop {
        let (queued, last) = {
            let m = MIXER.lock();
            m.clients
                .iter()
                .find(|c| c.key == key)
                .map_or((false, 0), |c| {
                    (!c.ring.is_empty() || c.ncarry > 0, c.last_period)
                })
        };
        let played = sound::with(|d| d.periods_played).unwrap_or(u64::MAX);
        if (!queued && played >= last) || timer::now_ns() > end {
            return;
        }
        SPACE_WQ.wait_until_timeout(|| false, 5_000_000);
    }
}

/// Mix one period into `out` (interleaved stereo). Returns false if nobody had data.
fn mix(m: &mut Mixer, out: &mut [i16; PERIOD_FRAMES * 2]) -> bool {
    let mut acc = [0i32; PERIOD_FRAMES * 2];
    let mut any = false;
    let serial = m.submitted + 1;
    for c in m.clients.iter_mut() {
        c.refill();
        let n = c.ring.len().min(acc.len());
        if n == 0 {
            continue;
        }
        any = true;
        c.last_period = serial;
        for (a, s) in acc.iter_mut().zip(c.ring.drain(..n)) {
            *a += s as i32;
        }
        c.refill();
    }
    if !any {
        return false;
    }
    for (o, &a) in out.iter_mut().zip(acc.iter()) {
        if !(i16::MIN as i32..=i16::MAX as i32).contains(&a) {
            m.clipped += 1;
        }
        *o = a.clamp(i16::MIN as i32, i16::MAX as i32) as i16;
    }
    m.frames_mixed += PERIOD_FRAMES as u64;
    m.submitted = serial;
    true
}

fn mixer_thread() {
    let mut buf = [0i16; PERIOD_FRAMES * 2];
    loop {
        // System sound requests (file loading happens here, in thread context).
        while let Some(s) = REQUESTS.lock().pop_front() {
            if let Some(pcm) = load(s) {
                let mut m = MIXER.lock();
                let key = Key::System(m.next_sys);
                m.next_sys += 1;
                let mut c = Client::new(key, timer::now_ns());
                c.pending = Some((pcm, 0));
                m.clients.push(c);
                SYS_PLAYED.fetch_add(1, Ordering::Relaxed);
            }
        }
        let now = timer::now_ns();
        sound::with(|d| {
            d.reclaim();
            let mut m = MIXER.lock();
            let mut more = true;
            while d.can_submit() {
                if !mix(&mut m, &mut buf) {
                    more = false;
                    break;
                }
                m.last_data = now;
                d.submit(|bytes| {
                    for (k, s) in buf.iter().enumerate() {
                        bytes[2 * k..2 * k + 2].copy_from_slice(&s.to_le_bytes());
                    }
                });
            }
            // Start once the device buffer is full, or when that is all there is.
            if !d.running() && d.in_flight() > 0 && (d.in_flight() >= PERIODS || !more) && d.start()
            {
                m.starts += 1;
            }
            if d.running()
                && d.in_flight() == 0
                && m.clients.iter().all(|c| c.idle())
                && now.saturating_sub(m.last_data) > IDLE_STOP_NS
            {
                d.stop();
            }
            // Forget finished system sounds and long-idle writers.
            m.clients.retain(|c| match c.key {
                Key::System(_) => !c.idle(),
                Key::Pid(_) => !c.idle() || now.saturating_sub(c.last_write) < CLIENT_GC_NS,
            });
        });
        SPACE_WQ.wake_all();
        let busy = sound::with(|d| d.running() || d.in_flight() > 0).unwrap_or(false);
        MIX_WQ.wait_until_timeout(
            || KICK.swap(false, Ordering::AcqRel),
            if busy { 50_000_000 } else { 1_000_000_000 },
        );
    }
}

/// `/dev/audio`: write S16_LE 48 kHz stereo PCM. Blocks while the writer's ring is full.
/// ioctls: SNDCTL_DSP_SYNC (0x5001) waits until it has been played; MILK_AUDIO_SYSTEM
/// (0x4d01, arg = sound index) plays a system sound.
struct AudioDev {
    ino: u64,
    dev: u64,
}

const SNDCTL_DSP_SYNC: u32 = 0x5001;
/// milkOS: play system sound `arg` (0 notify, 1 error, 2 chime, 3 shutter) through
/// [`play_system`].
pub const MILK_AUDIO_SYSTEM: u32 = 0x4d01;

impl Inode for AudioDev {
    fn ino(&self) -> u64 {
        self.ino
    }
    fn dev(&self) -> u64 {
        self.dev
    }
    fn kind(&self) -> InodeType {
        InodeType::CharDev
    }
    fn stat(&self) -> Stat {
        let mut st = Stat::new(self.dev, self.ino, InodeType::CharDev, 0o666);
        st.rdev = makedev(14, 4); // Linux's /dev/audio
        st.blksize = (PERIOD_FRAMES * FRAME_BYTES) as u32;
        st
    }
    fn read_at(&self, _off: u64, _buf: &mut [u8]) -> Result<usize> {
        Err(Errno::EINVAL) // no capture
    }
    fn write_at(&self, _off: u64, buf: &[u8]) -> Result<usize> {
        write(sched::current_pid(), buf)
    }
    fn truncate(&self, _len: u64) -> Result<()> {
        Ok(())
    }
    fn ioctl(&self, cmd: u32, arg: usize) -> Result<usize> {
        match cmd {
            SNDCTL_DSP_SYNC => {
                drain(sched::current_pid());
                Ok(0)
            }
            MILK_AUDIO_SYSTEM => {
                let s = *Sound::ALL.get(arg).ok_or(Errno::EINVAL)?;
                play_system(s);
                Ok(0)
            }
            _ => Err(Errno::ENOTTY),
        }
    }
    fn poll(&self) -> u32 {
        let pid = sched::current_pid();
        let full = MIXER
            .lock()
            .clients
            .iter()
            .any(|c| c.key == Key::Pid(pid) && c.space() < 2 * PERIOD_FRAMES);
        if full { 0 } else { 0x4 }
    }
}

fn proc_audio() -> String {
    let mut s = String::new();
    let m = MIXER.lock();
    let _ = writeln!(
        s,
        "format: S16_LE {RATE} Hz stereo, {} ms periods",
        PERIOD_FRAMES * 1000 / RATE as usize
    );
    let _ = writeln!(s, "clients: {}", m.clients.len());
    for c in &m.clients {
        let who = match c.key {
            Key::Pid(p) => alloc::format!("pid {p}"),
            Key::System(n) => alloc::format!("system sound #{n}"),
        };
        let _ = writeln!(
            s,
            "  {who}: {} ms queued",
            c.ring.len() / 2 * 1000 / RATE as usize
        );
    }
    let _ = writeln!(
        s,
        "mixed: {} frames ({} ms), starts {}, clipped samples {}",
        m.frames_mixed,
        m.frames_mixed * 1000 / RATE as u64,
        m.starts,
        m.clipped
    );
    drop(m);
    let _ = writeln!(
        s,
        "system sounds played: {}",
        SYS_PLAYED.load(Ordering::Relaxed)
    );
    if let Some((run, fl, played, xr, err)) = sound::with(|d| {
        (
            d.running(),
            d.in_flight(),
            d.periods_played,
            d.xruns,
            d.ctl_errors,
        )
    }) {
        let _ = writeln!(
            s,
            "device: {}, {} periods in flight, {} played, {} xruns, {} control errors",
            if run { "running" } else { "stopped" },
            fl,
            played,
            xr,
            err
        );
    }
    s
}

/// Publish /dev/audio and /proc/audio and start the mixer thread, if there is a sound
/// device. Call after `sched::init` and `fs::init`.
pub fn init() {
    if !sound::present() {
        kprintln!("[audio] no sound device (qemu: -device virtio-sound-device,audiodev=...)");
        return;
    }
    let dev = crate::fs::devfs::ids().map_or(0, |ids| ids.dev);
    let node = Arc::new(AudioDev {
        ino: 0x000a_0d10,
        dev,
    });
    if let Err(e) = crate::fs::devfs::add_device("audio", node) {
        kprintln!("[audio] /dev/audio: {e:?}");
        return;
    }
    if let Some(root) = crate::fs::procfs::root() {
        root.add_file("audio", proc_audio);
    }
    drop(sched::spawn_prio(
        "audio",
        sched::Priority::High,
        mixer_thread,
    ));
    UP.store(true, Ordering::Release);
    kprintln!("[audio] /dev/audio up: S16_LE {RATE} Hz stereo, mixer thread started");
}
