test('basic methods', function () {
  var s = 'Hello, World';
  assertEq(s.length, 12);
  assertEq(s.charAt(1), 'e');
  assertEq(s[4], 'o');
  assertEq(s.charCodeAt(0), 72);
  assertEq(s.indexOf('o'), 4);
  assertEq(s.lastIndexOf('o'), 8);
  assertEq(s.includes('World'), true);
  assertEq(s.startsWith('Hell'), true);
  assertEq(s.endsWith('ld'), true);
  assertEq(s.slice(-5), 'World');
  assertEq(s.substring(5, 0), 'Hello');
  assertEq(s.substr(7, 3), 'Wor');
  assertEq(s.toUpperCase(), 'HELLO, WORLD');
  assertEq(s.toLowerCase(), 'hello, world');
  assertEq('  x  '.trim(), 'x');
  assertEq('  x  '.trimStart(), 'x  ');
  assertEq('  x  '.trimEnd(), '  x');
  assertEq('ab'.repeat(3), 'ababab');
  assertEq('5'.padStart(3, '0'), '005');
  assertEq('5'.padEnd(3, 'ab'), '5ab');
  assertEq('a-b-c'.split('-'), ['a', 'b', 'c']);
  assertEq('abc'.split(''), ['a', 'b', 'c']);
  assertEq('a,b,'.split(','), ['a', 'b', '']);
  assertEq('a b'.split(' ', 1), ['a']);
  assertEq(''.split(','), ['']);
  assertEq('abc'.split(), ['abc']);
  assertEq('x'.concat(1, null), 'x1null');
  assertEq('abc'.at(-1), 'c');
  assertEq('a'.codePointAt(0), 97);
  assertEq('😀'.codePointAt(0), 0x1F600);
  assertEq(String.fromCharCode(72, 105), 'Hi');
  assertEq(String.fromCodePoint(0x1F600).length, 2);
  assertEq(String.raw`a\nb${1}`, 'a\\nb1');
  assertEq('ß'.toUpperCase(), 'SS');
  assertEq('İ'.toLowerCase().length, 2);
  assertEq('ΑΣ'.toLowerCase(), 'ας');
  assertThrows(RangeError, function () { 'a'.repeat(-1); });
  assertThrows(TypeError, function () { String.prototype.trim.call(null); });
});
test('replace', function () {
  assertEq('aaa'.replace('a', 'b'), 'baa');
  assertEq('aaa'.replaceAll('a', 'b'), 'bbb');
  assertEq('abc'.replace('b', '[$&]'), 'a[b]c');
  assertEq('abc'.replace('b', "$`$'"), 'aacc');
  assertEq('abc'.replace('b', (m, i) => m.toUpperCase() + i), 'aB1c');
  assertEq('x'.replace('y', 'z'), 'x');
  assertEq('a.b.c'.replaceAll('.', '$$'), 'a$b$c');
});
test('compare and search', function () {
  assertEq('a'.localeCompare('b'), -1);
  assertEq('b'.localeCompare('a'), 1);
  assertEq('a'.localeCompare('a'), 0);
  assertEq(['b', 'a', 'C'].sort((x, y) => x.localeCompare(y)), ['a', 'b', 'C']);
  assertEq('abcabc'.indexOf('c', 3), 5);
  assertEq('abc'.indexOf(''), 0);
  assertEq('abc'.lastIndexOf('', 1), 1);
  assertEq('abc'.search('c'), 2);
  assertEq('abc'.match('b')[0], 'b');
});
test('conversions', function () {
  assertEq(String(123), '123');
  assertEq(String(-0), '0');
  assertEq(String(null), 'null');
  assertEq(String(undefined), 'undefined');
  assertEq(String(Symbol('s')), 'Symbol(s)');
  assertThrows(TypeError, function () { return '' + Symbol(); });
  assertEq(String([1, [2]]), '1,2');
  assertEq(new String('ab').length, 2);
  assertEq(typeof new String('x'), 'object');
  assertEq(new String('ab')[1], 'b');
  assertEq(Object.keys(new String('ab')), ['0', '1']);
  assertEq('a' < 'b', true);
  assertEq('abc'.normalize(), 'abc');
});
test('long strings', function () {
  var parts = [];
  for (var i = 0; i < 10000; i++) parts.push('x');
  var s = parts.join('');
  assertEq(s.length, 10000);
  var t = '';
  for (var j = 0; j < 10000; j++) t += 'y';
  assertEq(t.length, 10000);
  assertEq(t.charAt(9999), 'y');
  assertEq(t.indexOf('z'), -1);
});
test('unicode', function () {
  var s = 'a😀b';
  assertEq(s.length, 4);
  assertEq([...s].length, 3);
  assertEq(s.slice(1, 3), '😀');
  assertEq(encodeURIComponent('a b&c/é😀'), 'a%20b%26c%2F%C3%A9%F0%9F%98%80');
  assertEq(decodeURIComponent('%C3%A9%F0%9F%98%80'), 'é😀');
  assertEq(encodeURI('http://x.y/a b?q=1#f'), 'http://x.y/a%20b?q=1#f');
  assertThrows(URIError, function () { decodeURIComponent('%E0%A4%A'); });
  assertThrows(URIError, function () { encodeURIComponent('\uD800'); });
  assertEq(escape('a b'), 'a%20b');
  assertEq(unescape('%u0041%42'), 'AB');
});
