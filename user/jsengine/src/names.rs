//! Property names the engine itself uses, interned once per realm (and never collected), so
//! builtins compare keys by handle.

macro_rules! names {
    ($($id:ident = $s:expr),* $(,)?) => {
        #[allow(non_camel_case_types, dead_code, clippy::enum_variant_names)]
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        #[repr(u16)]
        pub(crate) enum N { $($id),* }
        pub(crate) const NAME_STRS: &[&str] = &[$($s),*];
    };
}

