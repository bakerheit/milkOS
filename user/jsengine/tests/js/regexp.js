test('exec and test', function () {
  var m = /(\d+)-(\d+)/.exec('call 555-1234 now');
  assertEq(m[0], '555-1234');
  assertEq(m[1], '555');
  assertEq(m.index, 5);
  assertEq(m.input, 'call 555-1234 now');
  assert(/^abc$/i.test('ABC'));
  assert(!/^abc$/.test('xabc'));
  var g = /o/g;
  assert(g.test('foo'));
  assertEq(g.lastIndex, 2);
  assert(g.test('foo'));
  assert(!g.test('foo'));
  assertEq(g.lastIndex, 0);
  var named = /(?<year>\d{4})-(?<month>\d{2})/.exec('2026-10');
  assertEq(named.groups.year, '2026');
  assertEq(named.groups.month, '10');
  assertEq(/a(b)?c/.exec('ac')[1], undefined);
  var y = /a/y;
  assert(!y.test('ba'));
  y.lastIndex = 1;
  assert(y.test('ba'));
});
test('string methods', function () {
  assertEq('a1b22c333'.match(/\d+/g), ['1', '22', '333']);
  assertEq('abc'.match(/x/g), null);
  assertEq('x-y_z'.replace(/[-_]/g, ' '), 'x y z');
  assertEq('john smith'.replace(/(\w+)\s(\w+)/, '$2, $1'), 'smith, john');
  assertEq('aaa'.replace(/a/g, (m, i) => i), '012');
  assertEq('2026-10-21'.replace(/(?<y>\d+)-(?<m>\d+)-(?<d>\d+)/, '$<d>/$<m>/$<y>'), '21/10/2026');
  assertEq('a, b,c'.split(/\s*,\s*/), ['a', 'b', 'c']);
  assertEq('a1b2c'.split(/(\d)/), ['a', '1', 'b', '2', 'c']);
  assertEq('abc'.split(/(?:)/), ['a', 'b', 'c']);
  assertEq(''.split(/x/), ['']);
  assertEq('test'.search(/s/), 2);
  var all = [...'a1b2'.matchAll(/[a-z](\d)/g)].map(m => m[1]);
  assertEq(all, ['1', '2']);
  assertThrows(TypeError, function () { 'x'.matchAll(/x/); });
  assertEq('aBc'.replace(/b/i, 'X'), 'aXc');
  assertEq('a.b.c'.replaceAll(/\./g, '/'), 'a/b/c');
  assertEq('x'.replace(/(y)?x/, '[$1]'), '[]');
});
test('syntax', function () {
  assert(/[\]]/.test(']'));
  assert(/\//.test('/'));
  assert(/[/]/.test('/'));
  assert(/a{2}/.test('aa') && !/^a{2}$/.test('aaa'));
  assert(/^a{1,2}$/.test('aa'));
  assert(/x{/.test('x{'));
  assert(/\bword\b/.test('a word here'));
  assert(/^\s+$/.test(' \t\n '));
  assert(/A/.test('A'));
  assert(/\x41/.test('A'));
  assert(/[\d-z]/.test('-'));
  assert(/(a)\1/.test('aa'));
  assert(/(?=a)a/.test('a'));
  assert(/(?!b)a/.test('a'));
  assert(/(?<=\$)\d/.test('$5'));
  assert(/(?<!\$)\d/.test('5'));
  assert(/./s.test('\n') && !/./.test('\n'));
  assert(/^b/m.test('a\nb'));
  assert(/\p{L}/u.test('é'));
  assert(/^.$/u.test('😀'));
  assert(/[😀]/u.test('😀'));
  assertThrows(SyntaxError, function () { new RegExp('('); });
  assertThrows(SyntaxError, function () { new RegExp('a', 'gg'); });
  assertThrows(SyntaxError, function () { new RegExp('[b-a]'); });
});
test('objects', function () {
  var r = new RegExp('a/b', 'gi');
  assertEq(r.source, 'a\\/b');
  assertEq(r.flags, 'gi');
  assertEq(String(r), '/a\\/b/gi');
  assert(r.global && r.ignoreCase && !r.multiline);
  assertEq(new RegExp('').source, '(?:)');
  var copy = new RegExp(r, 'm');
  assertEq(copy.flags, 'm');
  assertEq(RegExp(r), r);
  assertEq(r.lastIndex, 0);
  assertEq(Object.prototype.toString.call(r), '[object RegExp]');
  var lit1 = [], lit2;
  for (var i = 0; i < 2; i++) lit1.push(/x/g);
  assert(lit1[0] !== lit1[1], 'a literal makes a new object each time');
});
test('backtracking limits', function () {
  var evil = /(a+)+b/;
  var s = '';
  for (var i = 0; i < 30; i++) s += 'a';
  var threw = false;
  try { evil.test(s); } catch (e) { threw = e instanceof RangeError; }
  assert(threw, 'catastrophic pattern stops');
  assert(/(a|b)*c/.test('ababababababababababababc'));
});
test('case folding and classes', function () {
  assert(/[a-z]/i.test('Q'));
  assert(/Σ/i.test('σ'));
  assert(/\w/.test('_') && !/\w/.test('é'));
  assert(/[^abc]/.test('d') && !/[^abc]/.test('a'));
  assert(/\D\W\S/.test('a b'.replace(/./g, '!') + ' '));
});
