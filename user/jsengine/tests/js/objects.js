test('literals and access', function () {
  var k = 'dyn';
  var o = { a: 1, 'b-c': 2, 3: 'three', [k + 'X']: 4, f() { return this.a; } };
  assertEq(o.a, 1);
  assertEq(o['b-c'], 2);
  assertEq(o[3], 'three');
  assertEq(o['3'], 'three');
  assertEq(o.dynX, 4);
  assertEq(o.f(), 1);
  var a = 5, b = 6;
  var s = { a, b };
  assertEq(s.a + s.b, 11);
  assertEq({ __proto__: Array.prototype } instanceof Array, true);
});
test('key order', function () {
  var o = { b: 1, a: 2, 2: 'x', 1: 'y', [Symbol('s')]: 0 };
  o.c = 3;
  assertEq(Object.keys(o), ['1', '2', 'b', 'a', 'c']);
  var seen = [];
  for (var key in o) seen.push(key);
  assertEq(seen, ['1', '2', 'b', 'a', 'c']);
  delete o.b;
  o.b = 9;
  assertEq(Object.keys(o), ['1', '2', 'a', 'c', 'b']);
});
test('prototypes', function () {
  function Animal(name) { this.name = name; }
  Animal.prototype.speak = function () { return this.name + ' speaks'; };
  var a = new Animal('cat');
  assertEq(a.speak(), 'cat speaks');
  assert(a instanceof Animal);
  assertEq(Object.getPrototypeOf(a), Animal.prototype);
  assertEq(a.constructor, Animal);
  var child = Object.create(a);
  assertEq(child.speak(), 'cat speaks');
  assert(Animal.prototype.isPrototypeOf(child));
  assert(!child.hasOwnProperty('name'));
  assert(a.hasOwnProperty('name'));
  var bare = Object.create(null);
  assertEq(Object.getPrototypeOf(bare), null);
  bare.x = 1;
  assertEq(bare.x, 1);
  function Shape() {}
  Shape.prototype.area = function () { return 0; };
  function Sq(s) { this.s = s; }
  Sq.prototype = Object.create(Shape.prototype);
  Sq.prototype.constructor = Sq;
  Sq.prototype.area = function () { return this.s * this.s; };
  assertEq(new Sq(3).area(), 9);
  assert(new Sq(1) instanceof Shape);
  var o = {};
  o.__proto__ = { inherited: true };
  assertEq(o.inherited, true);
});
test('defineProperty', function () {
  var o = {};
  Object.defineProperty(o, 'x', { value: 1 });
  assertEq(o.x, 1);
  o.x = 2;
  assertEq(o.x, 1);
  assertEq(Object.keys(o), []);
  assertThrows(TypeError, function () { 'use strict'; o.x = 3; });
  assertThrows(TypeError, function () { Object.defineProperty(o, 'x', { value: 5 }); });
  var calls = 0;
  Object.defineProperty(o, 'g', { get: function () { calls++; return 7; }, configurable: true });
  assertEq(o.g + o.g, 14);
  assertEq(calls, 2);
  var d = Object.getOwnPropertyDescriptor(o, 'x');
  assertEq([d.value, d.writable, d.enumerable, d.configurable], [1, false, false, false]);
  Object.defineProperties(o, { p: { value: 'p', enumerable: true }, q: { value: 'q', writable: true } });
  assertEq(Object.keys(o), ['p']);
  assert(delete o.g);
  assert(!delete o.x);
});
test('freeze seal', function () {
  var o = Object.freeze({ a: 1, n: { b: 2 } });
  assert(Object.isFrozen(o));
  o.a = 5;
  o.z = 1;
  assertEq(o.a, 1);
  assertEq(o.z, undefined);
  o.n.b = 3;
  assertEq(o.n.b, 3);
  assertThrows(TypeError, function () { 'use strict'; o.a = 2; });
  var s = Object.seal({ a: 1 });
  s.a = 2;
  delete s.a;
  assertEq(s.a, 2);
  assert(Object.isSealed(s) && !Object.isFrozen(s));
  var p = Object.preventExtensions({ a: 1 });
  p.b = 1;
  assert(!('b' in p) && !Object.isExtensible(p));
  var arr = Object.freeze([1, 2]);
  arr[0] = 9;
  assertEq(arr[0], 1);
  assertThrows(TypeError, function () { arr.push(3); });
});
test('keys values entries assign', function () {
  var o = { a: 1, b: 2 };
  assertEq(Object.values(o), [1, 2]);
  assertEq(Object.entries(o).map(e => e.join('=')), ['a=1', 'b=2']);
  var t = Object.assign({}, o, null, { c: 3 }, 'xy');
  assertEq(Object.keys(t), ['0', '1', 'a', 'b', 'c']);
  assertEq(Object.fromEntries([['x', 1], ['y', 2]]).y, 2);
  assertEq(Object.fromEntries(new Map([['m', 5]])).m, 5);
  assertEq(Object.getOwnPropertyNames('ab'), ['0', '1', 'length']);
  var sym = Symbol('k');
  var so = { [sym]: 1, s: 2 };
  assertEq(Object.getOwnPropertySymbols(so).length, 1);
  assertEq(Object.keys(so), ['s']);
  assert(Object.hasOwn(so, 's'));
});
test('spread and rest', function () {
  var a = { x: 1, y: 2 };
  var b = { ...a, y: 3, z: 4 };
  assertEq([b.x, b.y, b.z], [1, 3, 4]);
  var { x, ...rest } = b;
  assertEq(x, 1);
  assertEq(Object.keys(rest), ['y', 'z']);
  var c = { ...null, ...undefined, ...'hi' };
  assertEq(c[1], 'i');
});
test('toString valueOf conversions', function () {
  var o = { valueOf() { return 42; }, toString() { return 'str'; } };
  assertEq(o + 1, 43);
  assertEq(`${o}`, 'str');
  assertEq(String(o), 'str');
  assertEq(o * 2, 84);
  var p = { [Symbol.toPrimitive](hint) { return hint; } };
  assertEq(`${p}`, 'string');
  assertEq(p + '', 'default');
  assertEq(+p, NaN);
  assertEq(Object.prototype.toString.call([]), '[object Array]');
  assertEq(Object.prototype.toString.call(null), '[object Null]');
  assertEq(Object.prototype.toString.call(function () {}), '[object Function]');
  assertEq(Object.prototype.toString.call(new Date(0)), '[object Date]');
  assertEq(Object.prototype.toString.call({ [Symbol.toStringTag]: 'Mine' }), '[object Mine]');
  assertEq(String({}), '[object Object]');
  assertThrows(TypeError, function () { return { toString: null, valueOf: null } + ''; });
});
test('property enumeration over chains', function () {
  var base = { inherited: 1 };
  var o = Object.create(base);
  o.own = 2;
  var keys = [];
  for (var k in o) keys.push(k);
  assertEq(keys, ['own', 'inherited']);
  var arr = [1, 2];
  arr.extra = 'e';
  var ks = [];
  for (var i in arr) ks.push(i);
  assertEq(ks, ['0', '1', 'extra']);
  var deleted = { a: 1, b: 2, c: 3 };
  var seen = [];
  for (var key in deleted) { seen.push(key); delete deleted.b; }
  assertEq(seen, ['a', 'c']);
});
