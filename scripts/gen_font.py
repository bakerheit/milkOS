#!/usr/bin/env python3
"""Generate kernel/src/font_data.rs from a GNU Unifont .hex file (8x16 glyphs only).

Usage: python3 scripts/gen_font.py /path/to/unifont-13.0.06.hex

Emits glyphs for U+0020..U+00FF (Latin-1; control chars 0x7F..0x9F and NBSP are blank)
plus a replacement glyph (U+FFFD) used for anything outside that range.
Each glyph is 16 bytes, one per row, MSB = leftmost pixel.
GNU Unifont is dual-licensed GPLv2+ with the font embedding exception, and SIL OFL 1.1.
See assets/fonts/UNIFONT-LICENSE.txt.
"""
import pathlib
import sys

FIRST, LAST = 0x20, 0xFF
BLANK = bytes(16)


def load(path):
    glyphs = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            cp, data = line.split(":")
            if len(data) != 32:  # 16x16 wide glyph, not for us
                continue
            glyphs[int(cp, 16)] = bytes.fromhex(data)
    return glyphs


def rows(b):
    return "[" + ", ".join(f"0x{x:02X}" for x in b) + "]"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    g = load(sys.argv[1])
    out = pathlib.Path(__file__).resolve().parent.parent / "kernel/src/font_data.rs"
    lines = [
        "// @generated by scripts/gen_font.py from GNU Unifont 13.0.06. Do not edit by hand.",
        "// GNU Unifont: SIL OFL 1.1 / GPLv2+ with font embedding exception, see assets/fonts/UNIFONT-LICENSE.txt.",
        "",
        f"/// First code point in `GLYPHS`.",
        f"pub const FIRST_CHAR: u32 = 0x{FIRST:02X};",
        f"/// Last code point in `GLYPHS`.",
        f"pub const LAST_CHAR: u32 = 0x{LAST:02X};",
        "",
        "/// 8x16 glyphs, 16 row bytes each, MSB is the leftmost pixel.",
        f"pub static GLYPHS: [[u8; 16]; {LAST - FIRST + 1}] = [",
    ]
    for cp in range(FIRST, LAST + 1):
        if 0x7F <= cp <= 0xA0:
            data = BLANK
        else:
            data = g.get(cp, BLANK)
        lines.append(f"    {rows(data)}, // U+{cp:04X}")
    lines += [
        "];",
        "",
        "/// Shown for characters outside `GLYPHS` (U+FFFD).",
        f"pub static REPLACEMENT: [u8; 16] = {rows(g[0xFFFD])};",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


main()
