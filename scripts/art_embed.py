#!/usr/bin/env python3
"""Decode milkOS's art (PNG) into raw tables the kernel embeds. Python 3 stdlib only (zlib):
no Pillow, so building milkOS needs nothing extra on the host. Run by kernel/build.rs:

    art_embed.py ART_DIR OUT_DIR

ART_DIR is docs/ui-concepts/art (icons/, wallpapers/, splash/). Writes OUT_DIR/*.bin and
OUT_DIR/art.rs, which kernel/src/art.rs includes:

* icons/<name>-<size>[-dark].png (sizes 16..96; the 512 masters are not embedded) and the
  Files file types icons/file-<kind>-<size>[-dark].png: ARGB as little-endian u32 (bytes
  B G R A), alpha not premultiplied, the format of the wm's sprites;
* wallpapers/wallpaper-<name>-1024x768.png and splash/splash[-night]-1024x768.png: RGB,
  either raw (3 bytes a pixel) or run-length coded (count 1..255, R, G, B), whichever is
  smaller.

Identical images (the accent tiles' -dark files are the light ones) are stored once.
"""
import hashlib
import os
import re
import struct
import sys
import zlib


def decode(path):
    """(width, height, rows of (r, g, b, a) tuples) for an 8-bit, non-interlaced PNG."""
    d = open(path, "rb").read()
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{path}: not a PNG")
    i, idat, hdr, plte, trns = 8, b"", None, None, None
    while i < len(d):
        n, = struct.unpack(">I", d[i:i + 4])
        t, body = d[i + 4:i + 8], d[i + 8:i + 8 + n]
        if zlib.crc32(t + body) & 0xFFFFFFFF != struct.unpack(">I", d[i + 8 + n:i + 12 + n])[0]:
            raise ValueError(f"{path}: bad CRC in {t!r}")
        if t == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif t == b"PLTE":
            plte = body
        elif t == b"tRNS":
            trns = body
        elif t == b"IDAT":
            idat += body
        i += 12 + n
    w, h, depth, ctype, _, _, interlace = hdr
    if depth != 8 or interlace != 0:
        raise ValueError(f"{path}: only 8-bit, non-interlaced PNGs (depth {depth})")
    bpp = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    raw = zlib.decompress(idat)
    stride = w * bpp
    rows, prev, k = [], bytearray(stride), 0
    for _ in range(h):
        f = raw[k]
        line = bytearray(raw[k + 1:k + 1 + stride])
        k += 1 + stride
        if f == 1:
            for x in range(bpp, stride):
                line[x] = (line[x] + line[x - bpp]) & 255
        elif f == 2:
            for x in range(stride):
                line[x] = (line[x] + prev[x]) & 255
        elif f == 3:
            for x in range(stride):
                a = line[x - bpp] if x >= bpp else 0
                line[x] = (line[x] + (a + prev[x]) // 2) & 255
        elif f == 4:
            for x in range(stride):
                a = line[x - bpp] if x >= bpp else 0
                b = prev[x]
                c = prev[x - bpp] if x >= bpp else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c))) & 255
        px = []
        for x in range(w):
            q = line[x * bpp:(x + 1) * bpp]
            if ctype == 6:
                px.append((q[0], q[1], q[2], q[3]))
            elif ctype == 2:
                px.append((q[0], q[1], q[2], 255))
            elif ctype == 0:
                px.append((q[0], q[0], q[0], 255))
            elif ctype == 4:
                px.append((q[0], q[0], q[0], q[1]))
            else:  # palette
                j = q[0]
                a = trns[j] if trns and j < len(trns) else 255
                px.append((plte[3 * j], plte[3 * j + 1], plte[3 * j + 2], a))
        rows.append(px)
        prev = line
    return w, h, rows


def argb(rows):
    out = bytearray()
    for row in rows:
        for r, g, b, a in row:
            if a == 0:
                r = g = b = 0
            out += bytes((b, g, r, a))
    return bytes(out)


def rgb_best(rows):
    """(is_rle, data): raw RGB or (count, r, g, b) runs, whichever is smaller."""
    raw = bytearray()
    rle = bytearray()
    for row in rows:
        for r, g, b, _ in row:
            raw += bytes((r, g, b))
    i, n = 0, len(raw) // 3
    while i < n:
        c = raw[3 * i:3 * i + 3]
        j = i + 1
        while j < n and j - i < 255 and raw[3 * j:3 * j + 3] == c:
            j += 1
        rle += bytes((j - i,)) + c
        i = j
    return (True, bytes(rle)) if len(rle) < len(raw) else (False, bytes(raw))


def main():
    art, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    blobs = {}  # sha -> (file name, length)
    lines = [
        "// @generated by scripts/art_embed.py from docs/ui-concepts/art. Do not edit.",
        "",
    ]

    def blob(data):
        key = hashlib.sha256(data).hexdigest()
        if key not in blobs:
            name = f"b{len(blobs)}"
            with open(os.path.join(out, name + ".bin"), "wb") as f:
                f.write(data)
            blobs[key] = (name, len(data))
            path = os.path.abspath(os.path.join(out, name + ".bin")).replace("\\", "/")
            lines.append(
                f'static {name.upper()}: Aligned<[u8; {len(data)}]> = Aligned(*include_bytes!("{path}"));'
            )
        return blobs[key][0].upper()

    icons = []
    pat = re.compile(r"^(?P<name>[a-z-]+?)-(?P<size>\d+)(?P<dark>-dark)?\.png$")
    icon_dir = os.path.join(art, "icons")
    for f in sorted(os.listdir(icon_dir)) if os.path.isdir(icon_dir) else []:
        m = pat.match(f)
        if not m or int(m["size"]) > 96:
            continue
        w, h, rows = decode(os.path.join(icon_dir, f))
        if w != h:
            continue
        icons.append((m["name"], w, bool(m["dark"]), blob(argb(rows))))
    images = []
    for sub, prefix in (("wallpapers", "wallpaper-"), ("splash", "splash")):
        d = os.path.join(art, sub)
        for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            m = re.match(r"^(?P<name>[a-z-]+)-(?P<w>\d+)x(?P<h>\d+)\.png$", f)
            if not m or not f.startswith(prefix):
                continue
            w, h, rows = decode(os.path.join(d, f))
            rle, data = rgb_best(rows)
            images.append((m["name"], w, h, rle, blob(data)))
    lines.append("")
    lines.append("pub static ICONS: &[IconArt] = &[")
    for name, size, dark, b in icons:
        lines.append(
            f'    IconArt {{ name: "{name}", size: {size}, dark: {str(dark).lower()}, data: &{b}.0 }},'
        )
    lines.append("];")
    lines.append("")
    lines.append("pub static IMAGES: &[ImageArt] = &[")
    for name, w, h, rle, b in images:
        lines.append(
            f'    ImageArt {{ name: "{name}", w: {w}, h: {h}, rle: {str(rle).lower()}, data: &{b}.0 }},'
        )
    lines.append("];")
    with open(os.path.join(out, "art.rs"), "w") as f:
        f.write("\n".join(lines) + "\n")
    total = sum(n for _, n in blobs.values())
    print(f"art_embed: {len(icons)} icons, {len(images)} images, {len(blobs)} blobs, {total} bytes")


if __name__ == "__main__":
    main()
