test('toString', function () {
  assertEq(String(1e21), '1e+21');
  assertEq(String(123456789012345680000), '123456789012345680000');
  assertEq(String(0.000001), '0.000001');
  assertEq(String(1e-7), '1e-7');
  assertEq(String(-1.5e-10), '-1.5e-10');
  assertEq((255).toString(16), 'ff');
  assertEq((255).toString(2), '11111111');
  assertEq((-255).toString(36), '-73');
  assertEq((0.5).toString(2), '0.1');
  assertEq(String(2 ** 53), '9007199254740992');
  assertEq(String(NaN), 'NaN');
  assertEq(String(-Infinity), '-Infinity');
  assertThrows(RangeError, function () { (1).toString(1); });
});
test('toFixed toPrecision toExponential', function () {
  assertEq((1.005).toFixed(2), '1.00');
  assertEq((1.45).toFixed(1), '1.4');
  assertEq((2.5).toFixed(0), '3');
  assertEq((-1.5).toFixed(0), '-2');
  assertEq((0).toFixed(2), '0.00');
  assertEq((123.456).toFixed(2), '123.46');
  assertEq((1e21).toFixed(2), '1e+21');
  assertEq((123.456).toPrecision(4), '123.5');
  assertEq((0.00001234).toPrecision(2), '0.000012');
  assertEq((1234567).toPrecision(2), '1.2e+6');
  assertEq((123456).toExponential(2), '1.23e+5');
  assertEq((0).toExponential(), '0e+0');
  assertEq((1.5).toExponential(), '1.5e+0');
  assertEq((1234.5678).toLocaleString(), '1,234.568');
  assertEq((-1000000).toLocaleString(), '-1,000,000');
});
test('parsing', function () {
  assertEq(Number('  42  '), 42);
  assertEq(Number('0x10'), 16);
  assertEq(Number(''), 0);
  assertEq(Number('1e3'), 1000);
  assert(isNaN(Number('12px')));
  assertEq(Number(null), 0);
  assert(isNaN(Number(undefined)));
  assertEq(Number(true), 1);
  assertEq(Number([5]), 5);
  assertEq(Number([]), 0);
  assert(isNaN(Number([1, 2])));
  assertEq(parseInt('42px'), 42);
  assertEq(parseInt('  -0x1A'), -26);
  assertEq(parseInt('101', 2), 5);
  assertEq(parseInt('z', 36), 35);
  assert(isNaN(parseInt('px')));
  assertEq(parseInt('123456789012345678901234567890'), 1.2345678901234568e29);
  assertEq(parseFloat('3.14abc'), 3.14);
  assertEq(parseFloat('.5'), 0.5);
  assertEq(parseFloat('-Infinityx'), -Infinity);
  assertEq(+'  7 ', 7);
  assertEq(Number('0b11'), 3);
  assert(isNaN(Number('-0x10')));
});
test('statics', function () {
  assert(Number.isInteger(5) && !Number.isInteger(5.5));
  assert(Number.isSafeInteger(2 ** 53 - 1) && !Number.isSafeInteger(2 ** 53));
  assert(Number.isNaN(NaN) && !Number.isNaN('NaN'));
  assert(isNaN('NaN'));
  assert(Number.isFinite(1) && !Number.isFinite('1'));
  assertEq(Number.MAX_SAFE_INTEGER, 9007199254740991);
  assertEq(Number.EPSILON, 2 ** -52);
  assertEq(Number.parseInt, parseInt);
  assertEq(new Number(5) + 1, 6);
});
test('math', function () {
  assertEq(Math.max(), -Infinity);
  assertEq(Math.min(1, -2, 3), -2);
  assert(isNaN(Math.max(1, NaN)));
  assertEq(Math.round(2.5), 3);
  assertEq(Math.round(-2.5), -2);
  assertEq(Math.round(0.49999999999999994), 0);
  assertEq(Math.floor(-1.5), -2);
  assertEq(Math.ceil(1.2), 2);
  assertEq(Math.trunc(-4.7), -4);
  assertEq(Math.sign(-3), -1);
  assertEq(Math.abs(-5), 5);
  assertEq(Math.sqrt(16), 4);
  assertEq(Math.cbrt(27), 3);
  assertEq(Math.pow(2, 10), 1024);
  assertEq(Math.hypot(3, 4), 5);
  assertEq(Math.clz32(1), 31);
  assertEq(Math.imul(0xffffffff, 5), -5);
  assertEq(Math.fround(5.5), 5.5);
  assertEq(Math.log10(1000), 3);
  assertEq(Math.log2(8), 3);
  assertEq(Math.sin(0), 0);
  assertEq(Math.cos(0), 1);
  assert(Math.abs(Math.sin(Math.PI)) < 1e-15);
  assert(Math.abs(Math.atan2(1, 1) - Math.PI / 4) < 1e-15);
  assertEq(Math.exp(0), 1);
  assertEq(Math.log(Math.E), 1);
  var r = Math.random();
  assert(r >= 0 && r < 1);
  assertEq(Object.prototype.toString.call(Math), '[object Math]');
});
test('boolean and symbol', function () {
  assertEq(Boolean(''), false);
  assertEq(Boolean('0'), true);
  assertEq(new Boolean(false) ? 1 : 2, 1);
  assertEq(true.toString(), 'true');
  var s = Symbol('desc');
  assertEq(s.description, 'desc');
  assertEq(s.toString(), 'Symbol(desc)');
  assert(Symbol.for('k') === Symbol.for('k'));
  assertEq(Symbol.keyFor(Symbol.for('k')), 'k');
  assertEq(Symbol.keyFor(s), undefined);
  assertThrows(TypeError, function () { new Symbol(); });
  var o = { [s]: 1 };
  assertEq(o[s], 1);
  assertEq(Object.keys(o).length, 0);
  assertEq(typeof Symbol.iterator, 'symbol');
});
