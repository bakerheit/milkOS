#!/usr/bin/env python3
"""Generate user/webengine/src/html/entities.rs: the HTML named character references (the
WHATWG table, as Python ships it in html.entities.html5), sorted for binary search.

Each entry is the name without the '&' (with its ';' when the table has one; the legacy
names without ';' are entries too), and the one or two code points it stands for."""
import html.entities, os, sys

out = os.path.join(os.path.dirname(__file__), "..", "user", "webengine", "src", "html", "entities.rs")
items = sorted(html.entities.html5.items(), key=lambda kv: kv[0].encode())
lines = [
    "// Generated by scripts/gen_entities.py from the WHATWG named character references.",
    "// Do not edit by hand.",
    "",
    "/// (name without '&', code points); sorted by name bytes.",
    "pub static ENTITIES: &[(&str, [u32; 2])] = &[",
]
for name, val in items:
    cps = [ord(c) for c in val]
    assert 1 <= len(cps) <= 2, name
    while len(cps) < 2:
        cps.append(0)
    lines.append('    ("%s", [0x%x, 0x%x]),' % (name, cps[0], cps[1]))
lines.append("];")
lines.append("")
lines.append("/// The longest name (bytes).")
lines.append("pub const MAX_LEN: usize = %d;" % max(len(n) for n, _ in items))
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", len(items), "entities")
