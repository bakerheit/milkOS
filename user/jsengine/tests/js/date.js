test('construction and getters', function () {
  var d = new Date(Date.UTC(2026, 9, 21, 14, 3, 0));
  assertEq(d.getTime(), 1792591380000);
  assertEq(d.getUTCFullYear(), 2026);
  assertEq(d.getUTCMonth(), 9);
  assertEq(d.getUTCDate(), 21);
  assertEq(d.getUTCDay(), 3);
  assertEq(d.getUTCHours(), 14);
  assertEq(d.toISOString(), '2026-10-21T14:03:00.000Z');
  assertEq(new Date(0).toISOString(), '1970-01-01T00:00:00.000Z');
  assertEq(new Date(-1).toISOString(), '1969-12-31T23:59:59.999Z');
  assertEq(new Date(2026, 0, 31).getMonth(), 0);
  assertEq(new Date(2026, 1, 30).getDate(), 2);
  assertEq(new Date(99, 0).getFullYear(), 1999);
  assertEq(Date.now(), 1792591380000);
  assertEq(new Date().getTime(), 1792591380000);
  assert(isNaN(new Date('garbage').getTime()));
  assertEq(String(new Date(NaN)), 'Invalid Date');
  assertThrows(RangeError, function () { new Date(NaN).toISOString(); });
  assertEq(typeof Date(), 'string');
  assertEq(new Date(8.64e15 + 1).getTime(), NaN);
});
test('parsing', function () {
  assertEq(Date.parse('2026-10-21T14:03:00.000Z'), 1792591380000);
  assertEq(Date.parse('2026-10-21T14:03:00Z'), 1792591380000);
  assertEq(Date.parse('2026-10-21T16:03:00+02:00'), 1792591380000);
  assertEq(Date.parse('2026-10-21'), Date.UTC(2026, 9, 21));
  assertEq(Date.parse('2026-10'), Date.UTC(2026, 9, 1));
  assertEq(Date.parse('Wed, 21 Oct 2026 14:03:00 GMT'), 1792591380000);
  assertEq(Date.parse('October 21, 2026 14:03:00 UTC'), 1792591380000);
  assertEq(Date.parse('2026/10/21 14:03:00 GMT'), 1792591380000);
  assertEq(Date.parse(new Date(1792591380000).toUTCString()), 1792591380000);
  assertEq(Date.parse(new Date(1792591380000).toString()), 1792591380000);
});
test('setters and formatting', function () {
  var d = new Date(Date.UTC(2026, 0, 1));
  d.setUTCDate(32);
  assertEq(d.getUTCMonth(), 1);
  d.setUTCHours(25);
  assertEq(d.getUTCDate(), 2);
  d.setTime(0);
  assertEq(d.getTime(), 0);
  d.setUTCFullYear(2000, 1, 29);
  assertEq(d.toISOString().slice(0, 10), '2000-02-29');
  assertEq(new Date(0).toUTCString(), 'Thu, 01 Jan 1970 00:00:00 GMT');
  assertEq(new Date(0).toString(), 'Thu Jan 01 1970 00:00:00 GMT+0000 (Coordinated Universal Time)');
  assertEq(new Date(0).toLocaleDateString(), '1/1/1970');
  assertEq(new Date(0).toLocaleTimeString(), '12:00:00 AM');
  assertEq(new Date(Date.UTC(2026, 9, 21, 14, 3)).toLocaleString(), '10/21/2026, 2:03:00 PM');
  assertEq(JSON.stringify({ d: new Date(0) }), '{"d":"1970-01-01T00:00:00.000Z"}');
  assertEq(new Date(0) - new Date(1000), -1000);
  assertEq(typeof (new Date(0) + 1), 'string');
  assertEq(new Date(0).getTimezoneOffset(), 0);
});
