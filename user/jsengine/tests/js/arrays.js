test('construction and length', function () {
  assertEq(new Array(3).length, 3);
  assertEq(Array(1, 2).length, 2);
  assertEq([,,].length, 2);
  assertEq(Array.of(7).length, 1);
  assertThrows(RangeError, function () { new Array(-1); });
  var a = [1, 2, 3];
  a.length = 1;
  assertEq(a, [1]);
  a[5] = 'x';
  assertEq(a.length, 6);
  assertEq(a[3], undefined);
  assert(!(3 in a));
  var big = [];
  big[1e6] = 1;
  assertEq(big.length, 1000001);
  assertEq(Object.keys(big), ['1000000']);
  assertEq(Array.from({ length: 3 }, (_, i) => i * i), [0, 1, 4]);
  assertEq(Array.from('abc'), ['a', 'b', 'c']);
  assertEq(Array.isArray([]) && !Array.isArray({ length: 0 }), true);
});
test('mutators', function () {
  var a = [1, 2];
  assertEq(a.push(3, 4), 4);
  assertEq(a.pop(), 4);
  assertEq(a.shift(), 1);
  assertEq(a.unshift(0, 0.5), 4);
  assertEq(a, [0, 0.5, 2, 3]);
  var s = [1, 2, 3, 4, 5];
  assertEq(s.splice(1, 2), [2, 3]);
  assertEq(s, [1, 4, 5]);
  s.splice(1, 0, 'a', 'b');
  assertEq(s, [1, 'a', 'b', 4, 5]);
  assertEq(s.splice(-2), [4, 5]);
  assertEq([1, 2, 3].reverse(), [3, 2, 1]);
  assertEq([1, 2, 3, 4].fill(0, 1, 3), [1, 0, 0, 4]);
  assertEq([1, 2, 3, 4, 5].copyWithin(0, 3), [4, 5, 3, 4, 5]);
  var e = [];
  assertEq(e.pop(), undefined);
  assertEq(e.shift(), undefined);
});
test('sort', function () {
  assertEq([3, 1, 10, 2].sort(), [1, 10, 2, 3]);
  assertEq([3, 1, 10, 2].sort((a, b) => a - b), [1, 2, 3, 10]);
  assertEq(['b', undefined, 'a'].sort(), ['a', 'b', undefined]);
  var people = [{ n: 'a', age: 30 }, { n: 'b', age: 25 }, { n: 'c', age: 30 }, { n: 'd', age: 25 }];
  people.sort((x, y) => x.age - y.age);
  assertEq(people.map(p => p.n).join(''), 'bdac', 'stable');
  var big = [];
  for (var i = 0; i < 1000; i++) big.push((i * 7919) % 1000);
  big.sort((a, b) => a - b);
  var ok = true;
  for (var j = 0; j < 1000; j++) if (big[j] !== j) ok = false;
  assert(ok, 'sorted 1000');
  assertThrows(TypeError, function () { [1].sort(5); });
  var holes = [3, , 1];
  holes.sort();
  assertEq(holes.length, 3);
  assertEq(holes[0], 1);
  assert(!(2 in holes));
});
test('accessors', function () {
  var a = [1, 2, 3, 2, 1];
  assertEq(a.indexOf(2), 1);
  assertEq(a.lastIndexOf(2), 3);
  assertEq(a.indexOf(9), -1);
  assertEq(a.includes(3), true);
  assertEq([NaN].includes(NaN), true);
  assertEq([NaN].indexOf(NaN), -1);
  assertEq(a.slice(1, 3), [2, 3]);
  assertEq(a.slice(-2), [2, 1]);
  assertEq(a.join('-'), '1-2-3-2-1');
  assertEq([null, undefined, 1].join(), ',,1');
  assertEq(a.concat([4], 5, [[6]]).length, 8);
  assertEq(a.at(-1), 1);
  assertEq([1, [2, [3, [4]]]].flat(), [1, 2, [3, [4]]]);
  assertEq([1, [2, [3, [4]]]].flat(Infinity), [1, 2, 3, 4]);
  assertEq([1, 2].flatMap(x => [x, x * 10]), [1, 10, 2, 20]);
  assertEq(String([1, [2, 3]]), '1,2,3');
  var cyc = [1];
  cyc.push(cyc);
  assertEq(cyc.join(), '1,');
  assertEq([1, 2, 3].toString(), '1,2,3');
  assertEq([1234.5, 6].toLocaleString(), '1,234.5,6');
});
test('iteration methods', function () {
  var a = [1, 2, 3, 4];
  assertEq(a.map(x => x * 2), [2, 4, 6, 8]);
  assertEq(a.filter(x => x % 2), [1, 3]);
  assertEq(a.reduce((s, x) => s + x), 10);
  assertEq(a.reduce((s, x) => s + x, 10), 20);
  assertEq(a.reduceRight((s, x) => s + x, ''), '4321');
  assertEq(a.some(x => x > 3), true);
  assertEq(a.every(x => x > 0), true);
  assertEq(a.find(x => x > 2), 3);
  assertEq(a.findIndex(x => x > 2), 2);
  assertEq(a.findLast(x => x < 3), 2);
  assertEq(a.findLastIndex(x => x > 9), -1);
  var sum = 0;
  a.forEach(function (x) { sum += x * this.m; }, { m: 10 });
  assertEq(sum, 100);
  assertThrows(TypeError, function () { [].reduce((a, b) => a); });
  var visited = [];
  [1, , 3].forEach(x => visited.push(x));
  assertEq(visited, [1, 3]);
  assertEq([1, , 3].map(x => x * 2).length, 3);
  var mut = [1, 2, 3];
  var seen = [];
  mut.forEach(function (x, i) { seen.push(x); if (i === 0) mut.pop(); });
  assertEq(seen, [1, 2]);
});
test('generic methods on array-likes', function () {
  var al = { 0: 'a', 1: 'b', length: 2 };
  assertEq(Array.prototype.join.call(al, '+'), 'a+b');
  assertEq(Array.prototype.map.call(al, x => x.toUpperCase()), ['A', 'B']);
  Array.prototype.push.call(al, 'c');
  assertEq(al.length, 3);
  assertEq(Array.prototype.slice.call('xyz', 1), ['y', 'z']);
  function f() { return Array.prototype.indexOf.call(arguments, 'q'); }
  assertEq(f('p', 'q'), 1);
});
test('holes and sparse', function () {
  var s = [];
  s[2] = 'c';
  s[0] = 'a';
  assertEq(s.length, 3);
  assertEq(Object.keys(s), ['0', '2']);
  delete s[0];
  assertEq(s[0], undefined);
  assertEq(s.length, 3);
  var dense = [1, 2, 3];
  Object.defineProperty(dense, 1, { get() { return 'got'; } });
  assertEq(dense[1], 'got');
  assertEq(dense.join(), '1,got,3');
});
test('array length rules', function () {
  var a = [1, 2, 3];
  assertThrows(RangeError, function () { a.length = -1; });
  assertThrows(RangeError, function () { a.length = 1.5; });
  a.length = '2';
  assertEq(a.length, 2);
  var ro = [1];
  Object.defineProperty(ro, 'length', { writable: false });
  ro[5] = 1;
  assertEq(ro.length, 1);
  assertThrows(TypeError, function () { ro.push(2); });
});
